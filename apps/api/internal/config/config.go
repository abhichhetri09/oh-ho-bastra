package config

import (
	"errors"
	"fmt"
	"net/mail"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/joho/godotenv"
)

// Config holds application configuration from environment.
type Config struct {
	Port                int
	GinMode             string
	DatabaseURL         string
	JWTRefreshSecret    string
	JWTAccessSecret     string
	CloudinaryCloudName string
	CloudinaryAPIKey    string
	CloudinaryAPISecret string
	FrontendURL         string
	StripeSecretKey     string
	// StripeWebhookSecrets: the dashboard endpoint's signing secret and, in
	// development, the `stripe listen` one (STRIPE_WEBHOOK_SECRET_LOCAL).
	StripeWebhookSecrets []string
	CookieDomain         string
	OpenAPIPath          string
	TrustedProxies       []string // proxies allowed to set X-Forwarded-For; none by default

	// Order emails go out over SMTP; without SMTP_HOST they stay queued.
	SMTPHost     string
	SMTPPort     int
	SMTPUsername string
	SMTPPassword string
	SMTPTLS      string // starttls (default), tls or none
	MailFrom     string // e.g. "Oh Ho Bastra <orders@example.com>"

	AccessTokenTTL     time.Duration
	RefreshTokenTTL    time.Duration
	RefreshReuseWindow time.Duration // grace for a request that lost a concurrent refresh
	MaxSessionAge      time.Duration // absolute session lifetime, however often it's refreshed
}

// Load loads the repo-root .env.local (if present) then reads configuration from environment variables.
// No hardcoded URLs: PORT defaults to 5000 if unset; GIN_MODE defaults to "debug"; DATABASE_URL must be set in .env or env.
func Load() (*Config, error) {
	_ = godotenv.Load("../../.env.local") // ignore error if missing (e.g. in Docker, env comes from compose)

	port := 5000
	if p := os.Getenv("PORT"); p != "" {
		if v, err := strconv.Atoi(p); err == nil {
			port = v
		}
	}

	ginMode := os.Getenv("GIN_MODE")
	if ginMode == "" {
		ginMode = "debug"
	}

	dbURL := os.Getenv("DATABASE_URL")
	jwtRefreshSecret := os.Getenv("JWT_REFRESH_SECRET")
	jwtAccessSecret := os.Getenv("JWT_ACCESS_SECRET")
	cloudinaryCloudName := os.Getenv("CLOUDINARY_CLOUD_NAME")
	cloudinaryAPIKey := os.Getenv("CLOUDINARY_API_KEY")
	cloudinaryAPISecret := os.Getenv("CLOUDINARY_API_SECRET")
	frontendURL := strings.TrimRight(os.Getenv("FRONTEND_URL"), "/")
	var webhookSecrets []string
	for _, key := range []string{"STRIPE_WEBHOOK_SECRET", "STRIPE_WEBHOOK_SECRET_LOCAL"} {
		if v := strings.TrimSpace(os.Getenv(key)); v != "" {
			webhookSecrets = append(webhookSecrets, v)
		}
	}
	cookieDomain := os.Getenv("COOKIE_DOMAIN")

	// path to openapi.json (generated by packages/openapi, served at runtime)
	openapiPath := os.Getenv("OPENAPI_PATH")
	if openapiPath == "" {
		openapiPath = "openapi.json"
	}

	smtpPort := 587
	if p := strings.TrimSpace(os.Getenv("SMTP_PORT")); p != "" {
		v, err := strconv.Atoi(p)
		if err != nil {
			return nil, fmt.Errorf("SMTP_PORT: %q is not a number", p)
		}
		smtpPort = v
	}
	smtpTLS := strings.ToLower(strings.TrimSpace(os.Getenv("SMTP_TLS")))
	if smtpTLS == "" {
		smtpTLS = SMTPStartTLS
	}

	return &Config{
		Port:                 port,
		GinMode:              ginMode,
		DatabaseURL:          dbURL,
		JWTRefreshSecret:     jwtRefreshSecret,
		JWTAccessSecret:      jwtAccessSecret,
		CloudinaryCloudName:  cloudinaryCloudName,
		CloudinaryAPIKey:     cloudinaryAPIKey,
		CloudinaryAPISecret:  cloudinaryAPISecret,
		FrontendURL:          frontendURL,
		StripeSecretKey:      strings.TrimSpace(os.Getenv("STRIPE_SECRET_KEY")),
		StripeWebhookSecrets: webhookSecrets,
		CookieDomain:         cookieDomain,
		OpenAPIPath:          openapiPath,
		TrustedProxies:       splitList(os.Getenv("TRUSTED_PROXIES")),

		SMTPHost:     strings.TrimSpace(os.Getenv("SMTP_HOST")),
		SMTPPort:     smtpPort,
		SMTPUsername: os.Getenv("SMTP_USERNAME"),
		SMTPPassword: os.Getenv("SMTP_PASSWORD"),
		SMTPTLS:      smtpTLS,
		MailFrom:     strings.TrimSpace(os.Getenv("MAIL_FROM")),

		AccessTokenTTL:     15 * time.Minute,
		RefreshTokenTTL:    30 * 24 * time.Hour,
		RefreshReuseWindow: 30 * time.Second,
		MaxSessionAge:      90 * 24 * time.Hour,
	}, nil
}

// minJWTSecretLen is the minimum HMAC key size: 32 bytes for HS256.
const minJWTSecretLen = 32

// ValidateAuth fails fast on JWT secrets that would make tokens forgeable:
// empty or short keys, or one key shared by access and refresh tokens.
func (c *Config) ValidateAuth() error {
	if len(c.JWTAccessSecret) < minJWTSecretLen || len(c.JWTRefreshSecret) < minJWTSecretLen {
		return errors.New("JWT_ACCESS_SECRET and JWT_REFRESH_SECRET must each be at least 32 characters (openssl rand -hex 32)")
	}
	if c.JWTAccessSecret == c.JWTRefreshSecret {
		return errors.New("JWT_ACCESS_SECRET and JWT_REFRESH_SECRET must be different")
	}
	return nil
}

// SMTP_TLS modes.
const (
	SMTPStartTLS = "starttls" // upgrade a plain connection (port 587); required
	SMTPTLS      = "tls"      // implicit TLS from the start (port 465)
	SMTPNoTLS    = "none"     // plain text, for a local catcher such as Mailpit
)

// MailEnabled reports whether order emails are sent.
func (c *Config) MailEnabled() bool { return c.SMTPHost != "" }

// ValidateMail fails fast on an SMTP setup that could never send: no or a
// malformed sender, an unknown TLS mode or a bad port. Without SMTP_HOST
// mail is off and nothing is checked.
func (c *Config) ValidateMail() error {
	if !c.MailEnabled() {
		return nil
	}
	if c.MailFrom == "" {
		return errors.New("MAIL_FROM is required when SMTP_HOST is set (e.g. Oh Ho Bastra <orders@example.com>)")
	}
	if _, err := mail.ParseAddress(c.MailFrom); err != nil {
		return fmt.Errorf("MAIL_FROM %q is not an email address: %w", c.MailFrom, err)
	}
	switch c.SMTPTLS {
	case SMTPStartTLS, SMTPTLS, SMTPNoTLS:
	default:
		return fmt.Errorf("SMTP_TLS must be starttls, tls or none, not %q", c.SMTPTLS)
	}
	if c.SMTPPort < 1 || c.SMTPPort > 65535 {
		return fmt.Errorf("SMTP_PORT %d is out of range", c.SMTPPort)
	}
	if c.SMTPUsername != "" && c.SMTPPassword == "" {
		return errors.New("SMTP_PASSWORD is required with SMTP_USERNAME")
	}
	return nil
}

// splitList parses a comma-separated env value, dropping empty entries.
func splitList(v string) []string {
	var out []string
	for _, part := range strings.Split(v, ",") {
		if part = strings.TrimSpace(part); part != "" {
			out = append(out, part)
		}
	}
	return out
}
