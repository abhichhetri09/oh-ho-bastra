/**
 * Turns sqlc's JSON description of the queries (`.sqlc/codegen.json`, from
 * `sqlc generate`) into typed node-postgres functions in src/db/gen: one
 * file per queries/*.sql file, plus models.ts with a type per table.
 *
 *   bun run db:sqlc      (sqlc generate && tsx scripts/sqlc-ts.ts)
 *
 * Conventions, kept close to what sqlc generates for Go:
 * - rows keep the SQL column names (snake_case), so a row can be sent as
 *   JSON as it is;
 * - a query with no parameter takes only the client, one with a single
 *   parameter takes the value, and one with more takes an object;
 * - :one resolves to the row or null, :many to an array, :exec to nothing,
 *   :execrows and :execresult to the number of affected rows;
 * - a row whose columns are exactly a table's is typed as that table's
 *   model; sqlc.embed(table) becomes a nested object.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const input = join(root, ".sqlc", "codegen.json");
const outDir = join(root, "src", "db", "gen");

type SqlType = { name: string };
type Column = {
  name: string;
  not_null: boolean;
  is_array: boolean;
  array_dims?: number;
  type: SqlType;
  table: { name: string } | null;
  embed_table: { name: string } | null;
};
type Query = {
  name: string;
  cmd: string;
  text: string;
  filename: string;
  columns: Column[];
  params: { number: number; column: Column }[];
  comments: string[];
};
type Table = { rel: { name: string }; columns: Column[] };
type Codegen = {
  queries: Query[];
  catalog: { schemas: { name: string; tables: Table[] }[] };
};

// Columns whose nullability sqlc can't infer (the same overrides as the Go
// config): active_offer_price returns NULL without an active offer.
const nullable = new Set([
  "storefront_products.offer_price",
  "storefront_variants.offer_price",
  "variant_prices.offer_price",
]);

const scalar: Record<string, string> = {
  text: "string",
  varchar: "string",
  citext: "string",
  uuid: "string",
  bool: "boolean",
  boolean: "boolean",
  int2: "number",
  int4: "number",
  int8: "number", // parsed as numbers (src/db/pool.ts); all fit in 2^53
  integer: "number",
  bigint: "number",
  smallint: "number",
  float4: "number",
  float8: "number",
  real: "number",
  numeric: "string",
  date: "string", // "2026-10-13", as Go's pgtype.Date sends it
  timestamptz: "Date",
  timestamp: "Date",
  jsonb: "unknown",
  json: "unknown",
};

function tsType(col: Column, forParam = false): string {
  const name = col.type.name.replace(/^pg_catalog\./, "");
  let t = scalar[name] ?? "unknown";
  if (forParam && t === "Date") t = "Date | string";
  if (col.is_array || (col.array_dims ?? 0) > 0)
    t = `${t.includes("|") ? `(${t})` : t}[]`;
  const key = col.table ? `${col.table.name}.${col.name}` : "";
  const isNullable = !col.not_null || nullable.has(key);
  return isNullable && t !== "unknown" ? `${t} | null` : t;
}

const pascal = (s: string) =>
  s.replace(/(^|_)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const camel = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const singular = (s: string) =>
  s.endsWith("ies")
    ? s.slice(0, -3) + "y"
    : s.endsWith("s")
      ? s.slice(0, -1)
      : s;
const modelName = (table: string) => pascal(singular(table));

const codegen = JSON.parse(readFileSync(input, "utf8")) as Codegen;
const tables = new Map<string, Table>();
for (const schema of codegen.catalog.schemas) {
  if (schema.name !== "public") continue;
  for (const t of schema.tables) tables.set(t.rel.name, t);
}

/** The table a row type equals, when its columns are exactly that table's. */
function wholeTable(cols: Column[]): string | null {
  const first = cols[0]?.table?.name;
  if (!first || cols.some((c) => c.table?.name !== first || c.embed_table))
    return null;
  const table = tables.get(first);
  if (!table || table.columns.length !== cols.length) return null;
  return table.columns.every((c, i) => c.name === cols[i]!.name) ? first : null;
}

function uniqueNames(names: string[]): string[] {
  const seen = new Map<string, number>();
  return names.map((n, i) => {
    const base = n || `column_${i + 1}`;
    const count = (seen.get(base) ?? 0) + 1;
    seen.set(base, count);
    return count === 1 ? base : `${base}_${count}`;
  });
}

const prop = (name: string) =>
  /^[a-z_][a-z0-9_]*$/i.test(name) ? name : JSON.stringify(name);

// --- models ---------------------------------------------------------------
const models: string[] = [
  "// Code generated by scripts/sqlc-ts.ts from the migrations. DO NOT EDIT.",
  "",
];
for (const [name, table] of tables) {
  models.push(`export interface ${modelName(name)} {`);
  for (const c of table.columns) {
    models.push(`  ${prop(c.name)}: ${tsType({ ...c, table: { name } })};`);
  }
  models.push("}", "");
}

// --- queries --------------------------------------------------------------
const byFile = new Map<string, Query[]>();
for (const q of codegen.queries) {
  const list = byFile.get(q.filename) ?? [];
  list.push(q);
  byFile.set(q.filename, list);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "models.ts"), models.join("\n"));

const indexLines = [
  "// Code generated by scripts/sqlc-ts.ts. DO NOT EDIT.",
  "",
  'export type * from "./models";',
];

for (const [file, queries] of [...byFile].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const usedModels = new Set<string>();
  const body: string[] = [];

  for (const q of queries) {
    const fn = camel(q.name);
    const sqlName = `${fn}Sql`;
    const comments = q.comments.map((c) => `//${c}`);

    body.push(...comments);
    body.push(`export const ${sqlName} = ${JSON.stringify(q.text)};`, "");

    // parameters
    const paramNames = uniqueNames(q.params.map((p) => p.column.name));
    let signature = "db: Queryable";
    let values = "[]";
    if (q.params.length === 1) {
      signature += `, ${paramNames[0]}: ${tsType(q.params[0]!.column, true)}`;
      values = `[${paramNames[0]}]`;
    } else if (q.params.length > 1) {
      const iface = `${q.name}Params`;
      body.push(`export interface ${iface} {`);
      q.params.forEach((p, i) =>
        body.push(`  ${prop(paramNames[i]!)}: ${tsType(p.column, true)};`),
      );
      body.push("}", "");
      signature += `, p: ${iface}`;
      values = `[${paramNames.map((n) => `p[${JSON.stringify(n)}]`).join(", ")}]`;
    }

    // result rows
    let rowType = "";
    let mapRow = "";
    if (q.cmd === ":one" || q.cmd === ":many") {
      const table = wholeTable(q.columns);
      const embeds = q.columns.some((c) => c.embed_table);
      if (table) {
        rowType = modelName(table);
        usedModels.add(rowType);
      } else {
        rowType = `${q.name}Row`;
        const names = uniqueNames(
          q.columns.map((c) =>
            c.embed_table ? singular(c.embed_table.name) : c.name,
          ),
        );
        body.push(`export interface ${rowType} {`);
        q.columns.forEach((c, i) => {
          if (c.embed_table) {
            const m = modelName(c.embed_table.name);
            usedModels.add(m);
            body.push(`  ${prop(names[i]!)}: ${m};`);
          } else {
            body.push(`  ${prop(names[i]!)}: ${tsType(c)};`);
          }
        });
        body.push("}", "");
      }
      if (embeds) {
        // array rows: an embedded table spans one result column per table column
        const parts: string[] = [];
        let at = 0;
        const names = uniqueNames(
          q.columns.map((c) =>
            c.embed_table ? singular(c.embed_table.name) : c.name,
          ),
        );
        q.columns.forEach((c, i) => {
          if (c.embed_table) {
            const t = tables.get(c.embed_table.name)!;
            const fields = t.columns
              .map((tc, j) => `${prop(tc.name)}: r[${at + j}]`)
              .join(", ");
            parts.push(`${prop(names[i]!)}: { ${fields} }`);
            at += t.columns.length;
          } else {
            parts.push(`${prop(names[i]!)}: r[${at++}]`);
          }
        });
        mapRow = `(r: unknown[]) => ({ ${parts.join(", ")} }) as ${rowType}`;
      }
    }

    const call = mapRow
      ? `db.query({ text: ${sqlName}, values: ${values}, rowMode: "array" })`
      : `db.query(${sqlName}, ${values})`;

    switch (q.cmd) {
      case ":one":
        body.push(
          `export async function ${fn}(${signature}): Promise<${rowType} | null> {`,
          `  const { rows } = await ${call};`,
          mapRow
            ? `  return rows[0] ? (${mapRow})(rows[0]) : null;`
            : `  return (rows[0] as ${rowType} | undefined) ?? null;`,
          "}",
        );
        break;
      case ":many":
        body.push(
          `export async function ${fn}(${signature}): Promise<${rowType}[]> {`,
          `  const { rows } = await ${call};`,
          mapRow
            ? `  return rows.map(${mapRow});`
            : `  return rows as ${rowType}[];`,
          "}",
        );
        break;
      case ":exec":
        body.push(
          `export async function ${fn}(${signature}): Promise<void> {`,
          `  await ${call};`,
          "}",
        );
        break;
      case ":execrows":
      case ":execresult":
        body.push(
          `/** Resolves to the number of affected rows. */`,
          `export async function ${fn}(${signature}): Promise<number> {`,
          `  const { rowCount } = await ${call};`,
          "  return rowCount ?? 0;",
          "}",
        );
        break;
      default:
        throw new Error(`${q.name}: unsupported command ${q.cmd}`);
    }
    body.push("");
  }

  const module = file.replace(/\.sql$/, "");
  const header = [
    `// Code generated by scripts/sqlc-ts.ts from queries/${file}. DO NOT EDIT.`,
    "",
    'import type { Queryable } from "../queryable";',
  ];
  if (usedModels.size) {
    header.push(
      `import type { ${[...usedModels].sort().join(", ")} } from "./models";`,
    );
  }
  writeFileSync(
    join(outDir, `${module}.ts`),
    [...header, "", ...body].join("\n"),
  );
  indexLines.push(`export * from "./${module}";`);
}

writeFileSync(join(outDir, "index.ts"), indexLines.join("\n") + "\n");
console.log(
  `sqlc-ts: ${codegen.queries.length} queries in ${byFile.size} files → src/db/gen`,
);
